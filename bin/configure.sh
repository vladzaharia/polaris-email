#!/usr/bin/env bash
# configure.sh — interactively (re)write .env.deploy, then re-render wrangler.local.jsonc files.
set -euo pipefail
# shellcheck source=bin/_lib.sh
source "$(dirname "$0")/_lib.sh"

cd "$ROOT"

# Load existing values to default the prompts.
if [[ -f "$ENV_FILE" ]]; then
  # shellcheck disable=SC1090
  source "$ENV_FILE"
fi

prompt() {
  local var="$1" desc="$2" default="${3:-}" secret="${4:-0}"
  local current="${!var:-$default}"
  local val
  if [[ "$secret" == "1" ]]; then
    printf '%s (%s) [hidden, enter to keep current]: ' "$var" "$desc" >&2
    if [[ -n "$current" ]]; then
      read -rs val || true
      echo >&2
      if [[ -z "$val" ]]; then val="$current"; fi
    else
      read -rs val || true
      echo >&2
    fi
  else
    if [[ -n "$current" ]]; then
      printf '%s (%s) [%s]: ' "$var" "$desc" "$current" >&2
    else
      printf '%s (%s): ' "$var" "$desc" >&2
    fi
    read -r val || true
    if [[ -z "$val" ]]; then val="$current"; fi
  fi
  printf '%s' "$val"
}

echo "polaris-email configure — values are written to .env.deploy (gitignored)."
echo "Press enter to keep current values shown in [brackets]."
echo

CF_ACCOUNT_ID="$(prompt CF_ACCOUNT_ID "Cloudflare account ID" "${CF_ACCOUNT_ID:-}")"
CF_API_TOKEN="$(prompt CF_API_TOKEN "Cloudflare API token (optional, for CI/DNS apply)" "${CF_API_TOKEN:-}" 1)"
CF_ZONE_ID="$(prompt CF_ZONE_ID "Cloudflare zone ID for POLARIS_DOMAIN (optional)" "${CF_ZONE_ID:-}")"
POLARIS_DOMAIN="$(prompt POLARIS_DOMAIN "primary domain (e.g. example.com)" "${POLARIS_DOMAIN:-}")"
POLARIS_API_HOSTNAME="$(prompt POLARIS_API_HOSTNAME "API hostname" "${POLARIS_API_HOSTNAME:-polaris-email-api.workers.dev}")"
TS_TAILNET="$(prompt TS_TAILNET "Tailscale tailnet (e.g. tail-scales.ts.net) — leave empty if no bridge" "${TS_TAILNET:-}")"
TS_OAUTH_CLIENT_SECRET="$(prompt TS_OAUTH_CLIENT_SECRET "Tailscale OAuth client secret, tskey-client-... (only needed for make bridge-up)" "${TS_OAUTH_CLIENT_SECRET:-}" 1)"
BRIDGE_HOST="$(prompt BRIDGE_HOST "Bridge FQDN on the tailnet (e.g. polaris-email.\$TS_TAILNET)" "${BRIDGE_HOST:-polaris-email.${TS_TAILNET:-example.ts.net}}")"
ALERT_WEBHOOK="$(prompt ALERT_WEBHOOK "Alert webhook URL (synthetic + staleness)" "${ALERT_WEBHOOK:-https://alerts.example.com/polaris-email}")"
SYNTHETIC_FROM="$(prompt SYNTHETIC_FROM "Synthetic monitor from-address" "${SYNTHETIC_FROM:-synthetic@${POLARIS_DOMAIN:-example.com}}")"
SYNTHETIC_TO="$(prompt SYNTHETIC_TO "Synthetic monitor to-address" "${SYNTHETIC_TO:-synthetic@in.${POLARIS_DOMAIN:-example.com}}")"
OIDC_ISSUER="$(prompt OIDC_ISSUER "Panel OIDC issuer URL (optional)" "${OIDC_ISSUER:-}")"
OIDC_CLIENT_ID="$(prompt OIDC_CLIENT_ID "Panel OIDC client ID (optional)" "${OIDC_CLIENT_ID:-}")"
SIDECAR_TAG="$(prompt SIDECAR_TAG "Bridge sidecar image tag (default: latest main SHA)" "${SIDECAR_TAG:-latest}")"

# Write atomically with mode 0600.
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT
cat > "$TMP" <<EOF
# polaris-email deploy config — generated by bin/configure.sh. Re-run safely.
# DO NOT COMMIT. .env.deploy is gitignored.
CF_ACCOUNT_ID="$CF_ACCOUNT_ID"
CF_API_TOKEN="$CF_API_TOKEN"
CF_ZONE_ID="$CF_ZONE_ID"
POLARIS_DOMAIN="$POLARIS_DOMAIN"
POLARIS_API_HOSTNAME="$POLARIS_API_HOSTNAME"
TS_TAILNET="$TS_TAILNET"
TS_OAUTH_CLIENT_SECRET="$TS_OAUTH_CLIENT_SECRET"
BRIDGE_HOST="$BRIDGE_HOST"
ALERT_WEBHOOK="$ALERT_WEBHOOK"
SYNTHETIC_FROM="$SYNTHETIC_FROM"
SYNTHETIC_TO="$SYNTHETIC_TO"
OIDC_ISSUER="$OIDC_ISSUER"
OIDC_CLIENT_ID="$OIDC_CLIENT_ID"
SIDECAR_TAG="$SIDECAR_TAG"
EOF
mv "$TMP" "$ENV_FILE"
chmod 0600 "$ENV_FILE"
trap - EXIT

echo
echo "wrote $ENV_FILE"

# If we already have CF resources captured, re-materialize the per-service local configs.
if [[ -f "$STATE_FILE" ]]; then
  echo "re-rendering services/*/wrangler.local.jsonc from templates..."
  "$ROOT/bin/render-wrangler-local.sh"
else
  echo "(no .deploy-state.json yet — run \`make bootstrap\` to create CF resources)"
fi

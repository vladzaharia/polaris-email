#!/usr/bin/env bash
# configure.sh — interactively (re)write .env.deploy, then re-render wrangler.local.jsonc files.
# Values are persisted after every prompt: if you Ctrl-C halfway through, progress isn't lost
# and the next run defaults to what you'd already entered.
set -euo pipefail
# shellcheck source=bin/_lib.sh
source "$(dirname "$0")/_lib.sh"

cd "$ROOT"

# Load existing values to default the prompts.
if [[ -f "$ENV_FILE" ]]; then
  # shellcheck disable=SC1090
  source "$ENV_FILE"
fi

# Single source of truth for what gets written to .env.deploy and in what order.
# Adding a field: append the name here and add a matching `ask` call below.
ENV_VARS=(
  CF_ACCOUNT_ID POLARIS_API_HOSTNAME
  CF_API_TOKEN CF_ZONE_ID
  SYNTHETIC_MONITOR_DOMAIN ALERT_WEBHOOK SYNTHETIC_FROM SYNTHETIC_TO
  OIDC_ISSUER OIDC_CLIENT_ID
  ANCHOR_S3_ENDPOINT ANCHOR_S3_BUCKET ANCHOR_S3_REGION
)

# Atomically rewrite .env.deploy from the current shell environment.
# Called after every prompt so partial progress is durable.
save_env() {
  local tmp; tmp="$(mktemp)"
  {
    echo "# polaris-email deploy config — generated by bin/configure.sh. Re-run safely."
    echo "# DO NOT COMMIT. .env.deploy is gitignored."
    for v in "${ENV_VARS[@]}"; do
      printf '%s="%s"\n' "$v" "${!v:-}"
    done
  } > "$tmp"
  chmod 0600 "$tmp"
  mv "$tmp" "$ENV_FILE"
}

prompt() {
  local var="$1" desc="$2" default="${3:-}" secret="${4:-0}"
  local current="${!var:-$default}"
  local val
  if [[ "$secret" == "1" ]]; then
    printf '%s (%s) [hidden, enter to keep current]: ' "$var" "$desc" >&2
    if [[ -n "$current" ]]; then
      read -rs val || true
      echo >&2
      if [[ -z "$val" ]]; then val="$current"; fi
    else
      read -rs val || true
      echo >&2
    fi
  else
    if [[ -n "$current" ]]; then
      printf '%s (%s) [%s]: ' "$var" "$desc" "$current" >&2
    else
      printf '%s (%s): ' "$var" "$desc" >&2
    fi
    read -r val || true
    if [[ -z "$val" ]]; then val="$current"; fi
  fi
  printf '%s' "$val"
}

# Prompt for $1, assign to the same variable name, persist .env.deploy.
# Args mirror prompt(): VAR, description, optional default, optional secret-flag.
ask() {
  local var="$1" desc="$2" default="${3:-}" secret="${4:-0}"
  local val
  val="$(prompt "$var" "$desc" "$default" "$secret")"
  printf -v "$var" '%s' "$val"
  save_env
}

echo "polaris-email configure — values are saved to .env.deploy (gitignored) after every prompt."
echo "Press enter to keep current values shown in [brackets]. Leave optional fields blank to skip."
echo

# Required (preflight enforces). Sending/receiving domains are managed via
# `polaris-email domain onboard`, not here.
ask CF_ACCOUNT_ID         "Cloudflare account ID"
ask POLARIS_API_HOSTNAME  "API hostname"                                  "${POLARIS_API_HOSTNAME:-polaris-email-api.workers.dev}"

# Cloudflare automation — optional, needed by `polaris-email domain onboard --apply`.
ask CF_API_TOKEN          "Cloudflare API token (optional)" "" 1
ask CF_ZONE_ID            "Cloudflare default zone ID (optional)"

# Synthetic monitoring — optional. SYNTHETIC_MONITOR_DOMAIN is the home domain for the
# synthetic test mailbox; it default-builds the FROM/TO addresses below.
ask SYNTHETIC_MONITOR_DOMAIN "Home domain for the synthetic monitor mailbox (optional, e.g. polaris.video)"
ask ALERT_WEBHOOK         "Alert webhook URL (optional; synthetic + staleness post failures here)"
ask SYNTHETIC_FROM        "Synthetic monitor from-address (optional)" "${SYNTHETIC_FROM:-${SYNTHETIC_MONITOR_DOMAIN:+synthetic@${SYNTHETIC_MONITOR_DOMAIN}}}"
ask SYNTHETIC_TO          "Synthetic monitor to-address (optional)"   "${SYNTHETIC_TO:-${SYNTHETIC_MONITOR_DOMAIN:+synthetic@in.${SYNTHETIC_MONITOR_DOMAIN}}}"

# Panel OIDC — optional, consumed by better-auth when the panel is fronted.
ask OIDC_ISSUER           "Panel OIDC issuer URL (optional)"
ask OIDC_CLIENT_ID        "Panel OIDC client ID (optional)"

# External Object-Lock target for audit anchors (Phase O1). Backblaze B2 is
# the default vendor; the access-key id + secret are pushed separately via
# `wrangler secret put ANCHOR_S3_*`. See infra/terraform/README.md.
ask ANCHOR_S3_ENDPOINT    "Anchor S3 endpoint URL"                                 "${ANCHOR_S3_ENDPOINT:-https://s3.us-west-005.backblazeb2.com}"
ask ANCHOR_S3_BUCKET      "Anchor S3 bucket (Object Lock COMPLIANCE)"              "${ANCHOR_S3_BUCKET:-polaris-anchors}"
ask ANCHOR_S3_REGION      "Anchor S3 region (e.g. us-west-005)"                    "${ANCHOR_S3_REGION:-us-west-005}"

echo
echo "wrote $ENV_FILE"

# If we already have CF resources captured, re-materialize the per-service local configs.
if [[ -f "$STATE_FILE" ]]; then
  echo "re-rendering services/*/wrangler.local.jsonc from templates..."
  "$ROOT/bin/render-wrangler-local.sh"
else
  echo "(no .deploy-state.json yet — run \`make bootstrap\` to create CF resources)"
fi

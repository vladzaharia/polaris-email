#!/usr/bin/env node
// Generate src/install.sh.gen.ts — a base64-encoded copy of src/install.sh
// embedded as a TS string default export. The Worker decodes this at module
// load and serves the result with content-type text/x-shellscript.
//
// Why: Cloudflare's WAF on api.cloudflare.com pattern-matches the multipart
// upload body during `wrangler deploy` and blocks any script bundle that
// contains shell-injection signatures (`curl -fsSL … | sh`, etc.). Bundling
// install.sh as a Text module puts the raw shell content in the upload
// payload and the WAF rejects the PUT with 403 + an HTML block page.
// Embedding the file as base64 inside the JS bundle leaves only
// `[A-Za-z0-9+/=]` in the upload — OWASP CRS at default paranoia doesn't
// decode it.
//
// install.sh remains the source of truth. wrangler.jsonc has a `build`
// hook that re-runs this script before every deploy, so the served content
// can never drift from the on-disk install.sh.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = dirname(here);

const src = join(root, 'src', 'install.sh');
const out = join(root, 'src', 'install.sh.gen.ts');

const sh = readFileSync(src);
const b64 = sh.toString('base64');

const ts = `// AUTO-GENERATED by scripts/gen-install-sh.mjs from src/install.sh.
// Do NOT hand-edit. Edit src/install.sh and run \`pnpm gen\` (or just
// \`wrangler deploy\`, which re-runs the generator via the build hook).
//
// The base64 indirection exists to bypass Cloudflare's WAF on
// api.cloudflare.com, which blocks multipart Worker uploads whose payload
// contains shell-injection signatures (\`curl … | sh\`, etc.). See
// scripts/gen-install-sh.mjs for the full rationale.
export default ${JSON.stringify(b64)};
`;

writeFileSync(out, ts);
// eslint-disable-next-line no-console -- build-time progress log
console.log(`wrote ${out} (${b64.length} base64 chars, ${sh.length} source bytes)`);
